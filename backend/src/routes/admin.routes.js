const router = require('express').Router();
const ctrl = require('../controllers/admin.controller');
const { auth, requireRole } = require('../middlewares/auth');
const A = [auth, requireRole('ADMIN')];
router.get('/stats',           ...A, ctrl.stats);
router.get('/users',           ...A, ctrl.listUsers);
router.patch('/users/:id',     ...A, ctrl.updateUser);
router.get('/agencies',        ...A, ctrl.listAgencies);
router.post('/agencies',       ...A, ctrl.createAgency);
router.patch('/agencies/:id',  ...A, ctrl.updateAgency);
router.delete('/agencies/:id', ...A, ctrl.deleteAgency);
router.get('/services',        ...A, ctrl.listServices);
router.post('/services',       ...A, ctrl.createService);
router.patch('/services/:id',  ...A, ctrl.updateService);
router.delete('/users/:id',        ...A, ctrl.deleteUser);
router.get('/appointments',        ...A, ctrl.listAppointments);
router.patch('/appointments/:id',   ...A, ctrl.updateAppointment);
router.get('/vehicles',            ...A, ctrl.listVehicles);
module.exports = router;
